#!/usr/bin/env python3
"""Export CMake compile commands and generate local clangd settings, including NVHPC."""

import argparse
import datetime
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess

MARKER = "# Generated by Aaron's prepare-clangd.py; local machine paths, do not commit."


def cache_values(path):
    values = {}
    for line in path.read_text().splitlines():
        if not line.startswith(("#", "//")) and ":" in line and "=" in line:
            key, value = line.split("=", 1)
            values[key.split(":", 1)[0]] = value
    return values


def build_environment(values, source):
    """Restore tool locations from the cache for MPI wrappers and CMake probes."""
    env = os.environ.copy()
    bins, libraries = [], []
    sdk = values.get("NVHPC_DIR")
    if sdk:
        root = Path(sdk)
        bins.append(root / "compilers/bin")
        libraries.append(root / "compilers/lib")
    cuda = values.get("CUDAToolkit_ROOT")
    if not cuda and values.get("CUDAToolkit_BIN_DIR"):
        cuda = str(Path(values["CUDAToolkit_BIN_DIR"]).parent)
    for prefix in (cuda, values.get("VVM_MPI_ROOT")):
        if prefix:
            root = Path(prefix)
            bins.append(root / "bin")
            libraries.extend((root / "lib", root / "lib64"))
    for lang in ("C", "CXX", "Fortran"):
        compiler = values.get("CMAKE_" + lang + "_COMPILER")
        if compiler:
            bins.append(Path(compiler).parent)
    for key, paths in (("PATH", bins), ("LD_LIBRARY_PATH", libraries)):
        existing = list(dict.fromkeys(str(p) for p in paths if p.is_dir()))
        if env.get(key):
            existing.append(env[key])
        if existing:
            env[key] = os.pathsep.join(existing)
    env["VVM_ROOT"] = str(source)
    return env


def header_database(source, build, entries):
    """Give project headers reliable commands so clangd won't borrow non-CUDA ones."""
    cpp = [
        e for e in entries if Path(e["file"]).suffix in (".cpp", ".cc", ".cxx", ".cu")
    ]
    if not cpp:
        raise ValueError("No C++ compile commands available for project headers")
    result = list(entries)
    known = {Path(e["file"]).resolve() for e in entries}
    headers = set()
    for directory in (source / "src", source / "include"):
        if directory.is_dir():
            headers.update(
                p.resolve()
                for p in directory.rglob("*")
                if p.suffix in (".h", ".hh", ".hpp", ".hxx", ".cuh") and p.is_file()
            )
    for header in sorted(headers - known):

        def score(entry):
            path = Path(entry["file"])
            common = 0
            for a, b in zip(path.parent.parts, header.parent.parts):
                if a != b:
                    break
                common += 1
            return (path.stem == header.stem, common, -len(path.parts))

        original = max(cpp, key=score)
        arguments = original.get("arguments") or shlex.split(original["command"])
        original_file = Path(original["file"])
        if not original_file.is_absolute():
            original_file = Path(original["directory"]) / original_file
        replaced = False
        command = []
        for arg in arguments:
            if not arg.startswith("-"):
                path = Path(arg)
                if not path.is_absolute():
                    path = Path(original["directory"]) / path
                if path.resolve() == original_file.resolve():
                    command.append(str(header))
                    replaced = True
                    continue
            command.append(arg)
        if not replaced:
            raise ValueError(
                "Cannot find source argument in command for " + str(original_file)
            )
        result.append(
            {
                "directory": original["directory"],
                "file": str(header),
                "arguments": command,
            }
        )
    destination = build / "aaron-clangd"
    destination.mkdir(exist_ok=True)
    (destination / "compile_commands.json").write_text(
        json.dumps(result, indent=2) + "\n"
    )
    return destination, len(result) - len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("build", type=Path, help="Existing CMake build directory")
    parser.add_argument(
        "--gcc-toolchain", type=Path, help="GCC prefix used by the NVHPC build"
    )
    parser.add_argument(
        "--cuda-path", type=Path, help="CUDA toolkit root; normally read from CMake"
    )
    parser.add_argument(
        "--skip-configure",
        action="store_true",
        help="Use an existing exported database without rerunning CMake",
    )
    parser.add_argument(
        "--gpu-arch",
        help="CUDA architecture, e.g. sm_90; normally read from compile commands",
    )
    args = parser.parse_args()
    build = args.build.resolve()
    cache = build / "CMakeCache.txt"
    if not cache.exists():
        parser.error(
            "Configure the project with CMake first; CMakeCache.txt is missing."
        )
    values = cache_values(cache)
    source = Path(values["CMAKE_HOME_DIRECTORY"])
    env = build_environment(values, source)
    if not args.skip_configure:
        configured = subprocess.run(
            [
                "cmake",
                "-S",
                str(source),
                "-B",
                str(build),
                "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
            ],
            env=env,
        )
        if configured.returncode:
            parser.exit(
                configured.returncode,
                "CMake configure failed; see the diagnostics above. "
                "No clangd settings were changed.\n",
            )
    values = cache_values(cache)
    database = build / "compile_commands.json"
    if not database.exists():
        parser.error(
            "CMake did not export compile_commands.json; use a Makefiles or Ninja generator."
        )
    entries = json.loads(database.read_text())
    cpp = [
        e for e in entries if Path(e["file"]).suffix in (".cpp", ".cc", ".cxx", ".cu")
    ]
    commands = [e.get("arguments") or shlex.split(e["command"]) for e in cpp]
    flags = [flag for command in commands for flag in command]
    nvhpc = bool(values.get("NVHPC_DIR")) or any(
        "nvhpc" in c[0] or "nvc++" in c[0] for c in commands
    )
    editor_database = build
    header_count = 0
    if nvhpc:
        editor_database, header_count = header_database(source, build, entries)
    config = [
        MARKER,
        "CompileFlags:",
        "  CompilationDatabase: " + json.dumps(str(editor_database)),
    ]
    if nvhpc:
        config += [
            "  Compiler: clang++",
            "  Remove: "
            + json.dumps(
                [
                    "-fast",
                    "-mp",
                    "-acc",
                    "--c++17",
                    "-extended-lambda",
                    "--expt-relaxed-constexpr",
                    "-expt-relaxed-constexpr",
                    "--relocatable-device-code=*",
                    "-rdc=*",
                    "-arch=*",
                    "-gpu=*",
                    "-Wext-lambda-captures-this",
                ]
            ),
        ]
        add = ["-std=c++17"]
        if "-mp" in flags:
            add += ["-fopenmp"]
        gcc = args.gcc_toolchain or (
            Path(values["VVM_GCC_TOOLCHAIN"])
            if values.get("VVM_GCC_TOOLCHAIN")
            else None
        )
        if gcc is None and shutil.which("g++"):
            gcc = Path(shutil.which("g++")).parent.parent
        if gcc:
            compiler = gcc / "bin/g++"
            if not compiler.is_file():
                parser.error(
                    "GCC toolchain must contain bin/g++; pass the correct --gcc-toolchain."
                )
            include = subprocess.check_output(
                [str(compiler), "-print-file-name=include"], text=True, env=env
            ).strip()
            add += ["--gcc-toolchain=" + str(gcc.resolve())]
            if Path(include).is_dir():
                add += ["-idirafter", include]
        mpi = values.get("VVM_MPI_ROOT")
        if mpi and (Path(mpi) / "include").is_dir():
            add += ["-isystem", str(Path(mpi) / "include")]
        gpu = values.get(
            "VVM_ENABLE_GPU", values.get("Kokkos_ENABLE_CUDA", "OFF")
        ).upper() in ("ON", "TRUE", "1")
        if gpu:
            cuda = args.cuda_path
            if not cuda and values.get("CUDAToolkit_BIN_DIR"):
                cuda = Path(values["CUDAToolkit_BIN_DIR"]).parent
            if not cuda or not (cuda / "include/cuda_runtime.h").is_file():
                parser.error(
                    "CUDA toolkit not found; pass --cuda-path with its root directory."
                )
            arch = args.gpu_arch or next(
                (f.split("=", 1)[1] for f in flags if re.fullmatch(r"-arch=sm_\d+", f)),
                None,
            )
            add += ["-xcuda", "--cuda-host-only", "--cuda-path=" + str(cuda.resolve())]
            if "--relocatable-device-code=true" in flags or "-rdc=true" in flags:
                add += ["-fgpu-rdc"]
            # Recent NVHPC SDKs keep cuRAND headers in math_libs, outside CUDA.
            curand = values.get("CUDA_curand_LIBRARY")
            if curand:
                math_include = Path(curand).parent.parent / "include"
                if (math_include / "curand_mtgp32_kernel.h").is_file():
                    add += ["-isystem", str(math_include)]
            if arch:
                add += ["--cuda-gpu-arch=" + arch]
        config += ["  Add:"] + ["    - " + json.dumps(flag) for flag in add]
    target = source / ".clangd"
    if target.exists():
        backup_dir = build / ".aaron-clangd-backups"
        backup_dir.mkdir(exist_ok=True)
        backup = backup_dir / (
            "clangd-" + datetime.datetime.now().strftime("%Y%m%d-%H%M%S-%f")
        )
        shutil.copy2(target, backup)
        print("Previous settings backed up to", backup)
    target.write_text("\n".join(config) + "\n")
    print(
        "Wrote",
        target,
        "using",
        len(entries),
        "source and",
        header_count,
        "explicit header commands.",
    )
    print("Restart Neovim (or use :LspRestart clangd) to reload the project settings.")
    print(
        "Keep .clangd and compile_commands.json out of Git: they contain machine-specific paths."
    )


if __name__ == "__main__":
    main()
